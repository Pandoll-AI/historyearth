// Generic suffix translations for non-state groups.
export const PATTERNS = [
  [/hunter-?gatherers?/i, '수렵채집민'], [/pastoral nomads|pastoralists|nomads/i, '유목민'], [/farmers/i, '농경민'],
  [/fishers|fichers|shellfish|marine mammal hunters|foraging/i, '어로·채집민'], [/hunters/i, '수렵민'], [/culture/i, '문화'],
];
export function nameKo(n) {
  if (!n) return '';
  if (NAME_KO[n]) return NAME_KO[n];
  for (const [re, ko] of PATTERNS) if (re.test(n)) return ko;
  return n;
}
